export const TWO_HANDED_WEAPONS: ReadonlySet<string> = new Set([
  'greatsword', 'hammer', 'bow', 'crossbow',
]);

export function isTwoHandedWeapon(subType: string | undefined): boolean {
  return !!subType && TWO_HANDED_WEAPONS.has(subType);
}

