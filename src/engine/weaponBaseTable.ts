import { WeaponSubType, CharacterClassId } from '../types';

export interface WeaponBaseStat {
  subType: string;
  name: string;
  emoji: string;
  speedRating: 'S' | 'A' | 'B' | 'C';
  baseCooldown: number; // Attack cooldown in seconds
  baseRange: number; // Range in units
  baseArc: number; // Swing arc in radians (0 for straight)
  baseKnockback: number;
  baseDmgMult: number;
  baseCritChance: number;
  recommendedClass: CharacterClassId;
  defaultVfxType: string;
  defaultGlowColor: string;
  glowIntensity: number;
  combatArchetype: 'cleave' | 'slam' | 'rapid_flurry' | 'snipe' | 'pierce' | 'homing_elemental' | 'elemental_rapid';
  perkName: string;
  perkDescription: string;
  styleDescription: string;
}

